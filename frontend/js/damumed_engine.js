  /**
   * Evaluates Kazakhstan 3H Triage Category according to MH RK Order # ҚР ДСМ-39 / Order # 225
   * @param {Array<string>} selectedSyndromeIds
   * @param {Object} vitals
   * @returns {Object} Triage result with category, color, max wait time, and reasoning
   */
  evaluateTriage(selectedSyndromeIds = [], vitals = {}) {
    const sbp = vitals.sbp ? Number(vitals.sbp) : null;
    const dbp = vitals.dbp ? Number(vitals.dbp) : null;
    const hr = vitals.hr ? Number(vitals.hr) : null;
    const spo2 = vitals.spo2 ? Number(vitals.spo2) : null;
    const rr = vitals.rr ? Number(vitals.rr) : null;
    const temp = vitals.temp ? Number(vitals.temp) : null;
    const gcs = vitals.gcs ? Number(vitals.gcs) : null;
    const glucose = vitals.glucose ? Number(vitals.glucose) : null;

    const reasons = [];

    // --- 1. RED CATEGORY (1-я категория, 0 минут / Немедленно) ---
    // Vital parameters red flags:
    if (gcs !== null && gcs <= 12) {
      reasons.push(`Угнетение сознания: ШКГ ${gcs} баллов (≤ 12)`);
    }
    if (spo2 !== null && spo2 < 90) {
      reasons.push(`Критическая гипоксемия: SpO2 ${spo2}% (< 90%)`);
    }
    if (sbp !== null && sbp < 90) {
      reasons.push(`Гемодинамический коллапс / шок: САД ${sbp} мм рт. ст. (< 90)`);
    }
    if (hr !== null && (hr < 40 || hr > 140)) {
      reasons.push(`Жизнеугрожающая аритмия: ЧСС ${hr}/мин`);
    }
    if (rr !== null && (rr < 8 || rr > 32)) {
      reasons.push(`Тяжелое дыхательное расстройство: ЧДД ${rr}/мин`);
    }
    if (glucose !== null && (glucose < 2.8 || glucose > 25.0)) {
      reasons.push(`Критическая гликемия: ${glucose} ммоль/л`);
    }

    // Syndrome red flags:
    const redSyndromes = ['stroke_fast', 'anaphylaxis', 'convulsions_coma', 'trauma_bleeding'];
    selectedSyndromeIds.forEach(id => {
      if (redSyndromes.includes(id)) {
        const proto = this.protocols[id];
        if (proto) reasons.push(`Критический синдром: ${proto.name}`);
      }
    });

    if (reasons.length > 0) {
      return {
        category: 'RED',
        code: '1',
        title: '🔴 КРАСНАЯ ЗОНА (1-я категория триажа МЗ РК)',
        subtitle: 'Немедленная реанимационная помощь (Время до контакта: 0 минут)',
        bgClass: 'bg-red-950/80 border-red-500 text-red-200',
        badgeClass: 'bg-red-600 text-white',
        maxWaitMinutes: 0,
        reasons
      };
    }

    // --- 2. YELLOW CATEGORY (2-я категория, до 10-15 минут / Срочно) ---
    const yellowReasons = [];

    if (sbp !== null && (sbp >= 180 || (sbp < 100 && sbp >= 90))) {
      yellowReasons.push(`Высокое / сниженное давление: САД ${sbp} мм рт. ст.`);
    }
    if (dbp !== null && dbp >= 110) {
      yellowReasons.push(`Диастолическая гипертензия: ДАД ${dbp} мм рт. ст.`);
    }
    if (spo2 !== null && spo2 >= 90 && spo2 < 95) {
      yellowReasons.push(`Умеренная дыхательная недостаточность: SpO2 ${spo2}%`);
    }
    if (hr !== null && ((hr >= 105 && hr <= 140) || (hr >= 40 && hr <= 50))) {
      yellowReasons.push(`Тахикардия / брадикардия: ЧСС ${hr}/мин`);
    }
    if (rr !== null && rr >= 22 && rr <= 32) {
      yellowReasons.push(`Тахипноэ: ЧДД ${rr}/мин`);
    }
    if (temp !== null && (temp >= 39.0 || temp < 35.5)) {
      yellowReasons.push(`Высокая гипертермия / гипотермия: t ${temp}°C`);
    }

    const yellowSyndromes = ['acute_coronary', 'hypertensive_crisis', 'acute_abdomen', 'dyspnea_tela', 'renal_hepatic_colic'];
    selectedSyndromeIds.forEach(id => {
      if (yellowSyndromes.includes(id)) {
        const proto = this.protocols[id];
        if (proto) yellowReasons.push(`Срочный клинический синдром: ${proto.name}`);
      }
    });

    if (yellowReasons.length > 0) {
      return {
        category: 'YELLOW',
        code: '2',
        title: '🟡 ЖЕЛТАЯ ЗОНА (2-я категория триажа МЗ РК)',
        subtitle: 'Срочная помощь приёмного покоя (Время до контакта: до 10–15 минут)',
        bgClass: 'bg-amber-950/80 border-amber-500 text-amber-200',
        badgeClass: 'bg-amber-500 text-black font-bold',
        maxWaitMinutes: 15,
        reasons: yellowReasons
      };
    }

    // --- 3. GREEN CATEGORY (3-я категория, до 30-60 минут / Неотложная/плановая) ---
    return {
      category: 'GREEN',
      code: '3',
      title: '🟢 ЗЕЛЕНАЯ ЗОНА (3-я категория триажа МЗ РК)',
      subtitle: 'Неотложная / плановая помощь (Время до контакта: до 30–60 минут)',
      bgClass: 'bg-emerald-950/80 border-emerald-500 text-emerald-200',
      badgeClass: 'bg-emerald-600 text-white',
      maxWaitMinutes: 60,
      reasons: ['Витальные функции стабильны, признаков острой органной недостаточности не выявлено.']
    };
  }

